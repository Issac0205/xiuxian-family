/** 全部商路（目前只有凡人这一条；云深谷坊市是兑换，不算派遣）。 */
const TRADE_ROUTES = [MORTAL_ROUTE];
const ROUTE_MAP = Object.fromEntries(TRADE_ROUTES.map((r) => [r.id, r]));

/** 一趟商路的总回报（未计科技修正；带修正的版本见 formulas.tradeReward）。 */
function routeReward(route, incomeMult = 1) {
  return Math.round(route.cost * route.multiplier * incomeMult);
}

/** 一趟商路的净赚。 */
function routeProfit(route, incomeMult = 1) {
  return routeReward(route, incomeMult) - route.cost;
}

