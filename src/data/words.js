function validText(value, name, maxLen, allowEmpty=false) {
  if (typeof value !== 'string') throw new Error(name+'必须是文字');
  const t=value.trim();
  if ((!allowEmpty && !t) || t.length>maxLen) throw new Error(name+'长度应在'+(allowEmpty?'0':'1')+'–'+maxLen+'字之间');
  return t;
}
function normalizeQuestionBank(raw) {
  if (!raw || typeof raw !== 'object' || Array.isArray(raw)) throw new Error('题库文件顶层必须是 JSON 对象');
  if (raw.format !== 'xiuxian-question-bank' || raw.version !== 1) throw new Error('题库格式或版本不正确：需要 format="xiuxian-question-bank"、version=1');
  const title=validText(raw.title,'题库名称',80);
  const description=typeof raw.description === 'string' ? validText(raw.description,'题库说明',300,true) : '';
  if (!Array.isArray(raw.questions) || raw.questions.length<1 || raw.questions.length>BANK_MAX_QUESTIONS)
    throw new Error('questions 必须是 1–1000 道题的数组');
  const ids = new Set();
  const questions=raw.questions.map((q,index)=>{
    const row='第 '+(index+1)+' 题：';
    if (!q || typeof q !== 'object' || Array.isArray(q)) throw new Error(row+'应为对象');
    const id=validText(q.id,row+'id',80);
    if (!/^[a-zA-Z0-9][a-zA-Z0-9_-]*$/.test(id)) throw new Error(row+'id 仅支持英文字母、数字、下划线、连接符');
    if (ids.has(id)) throw new Error(row+'id 重复：'+id);
    ids.add(id);
    const question=validText(q.question,row+'题干',600);
    if (!Array.isArray(q.options) || q.options.length!==4) throw new Error(row+'options 必须恰好四个选项');
    const options=q.options.map((o,j)=>validText(o,row+'选项 '+ 'ABCD'[j],300));
    if (new Set(options).size!==4) throw new Error(row+'四个选项不能重复');
    let answer=q.answer;
    if (typeof answer==='string' && /^[A-Da-d]$/.test(answer.trim())) answer=answer.trim().toUpperCase().charCodeAt(0)-65;
    if (!Number.isInteger(answer) || answer<0 || answer>3) throw new Error(row+'answer 必须是 A / B / C / D 或 0–3');
    const explanation=typeof q.explanation === 'string' ? validText(q.explanation,row+'解析',1200,true) : '';
    const source=typeof q.source === 'string' ? validText(q.source,row+'出处',200,true) : '';
    return {id,question,options,answer,explanation,source};
  });
  return {title,description,questions};
}
