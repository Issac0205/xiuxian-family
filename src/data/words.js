function makeActiveQuestion(state, rng=Math.random) {
  const bank=activeQuestionBank();
  if (!bank) return makeQuestion(state,rng);
  const stats=state.customQuizStats?.[bank.id] || {};
  const target=weightedPick(bank.questions,q=>wordWeight(stats[q.id]),rng);
  // 打乱显示位置，不会暴露源文件的固定答案位置
  const indices=shuffle([0,1,2,3],rng);
  return {
    wordId:target.id, customBankId:bank.id,
    word:target.question, phonetic:target.source || '',
    answer:target.options[target.answer],
    options:indices.map(i=>target.options[i]),
    correctIndex:indices.indexOf(target.answer),
    explanation:target.explanation || '', source:target.source || ''
  };
}
function recordCustomAnswer(state,question,pickedIndex) {
  const correct=pickedIndex===question.correctIndex;
  if (!state.customQuizStats) state.customQuizStats={};
  if (!state.customWrongBooks) state.customWrongBooks={};
  const stats=state.customQuizStats[question.customBankId] || (state.customQuizStats[question.customBankId]={});
  const row=stats[question.wordId] || (stats[question.wordId]={seen:0,right:0,wrong:0});
  row.seen+=1;
  const q=state.quiz;
  q.total+=1;
  if (correct) {
    row.right+=1; q.right+=1; q.streak+=1; q.bestStreak=Math.max(q.bestStreak,q.streak);
  } else {
    row.wrong+=1; q.wrong+=1; q.streak=0;
    const prev=state.customWrongBooks[question.customBankId] || [];
    state.customWrongBooks[question.customBankId]=[question.wordId,...prev.filter(id=>id!==question.wordId)].slice(0,200);
  }
  return correct;
}
